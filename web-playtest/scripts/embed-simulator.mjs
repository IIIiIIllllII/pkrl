import {createHash} from 'node:crypto'
import {readdirSync, readFileSync, statSync, writeFileSync} from 'node:fs'
import {dirname, join, relative, resolve} from 'node:path'
import {fileURLToPath} from 'node:url'
import {gzipSync} from 'node:zlib'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const vendor = join(root, 'vendor/pokemon-showdown')
const output = join(root, 'server/generated-runtime.ts')

function files(directory) {
  return readdirSync(directory).sort().flatMap(name => {
    const path = join(directory, name)
    return statSync(path).isDirectory() ? files(path) : [path]
  })
}

const archive = Object.fromEntries(files(vendor).map(path => [
  relative(vendor, path).replaceAll('\\', '/'),
  readFileSync(path).toString('base64'),
]))
const compressed = gzipSync(Buffer.from(JSON.stringify(archive)), {level: 9, mtime: 0})
const digest = createHash('sha256').update(compressed).digest('hex').slice(0, 16)

writeFileSync(output,
  `// Generated by scripts/embed-simulator.mjs; do not edit.\n` +
  `export const PINNED_RUNTIME_ID = ${JSON.stringify(digest)}\n` +
  `export const PINNED_RUNTIME_GZIP_BASE64 = ${JSON.stringify(compressed.toString('base64'))}\n`,
)
console.log(`embedded ${Object.keys(archive).length} pinned simulator files (${compressed.length} compressed bytes)`)
